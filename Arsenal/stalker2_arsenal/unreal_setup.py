"""Sets up a new weapon in ZoneKit from a template weapon: exports the template's first-person files for
Blender, checks the assets that stay in ZoneKit out into your mod, and renames them to the new weapon name.

Generated by the Stalker 2 Arsenal Blender add-on (1. Set Up panel). Run it once from the ZoneKit Python bar:

    py "<path to this file>"

Settings are baked into CONFIG by the add-on. Run it with a normal Python (outside ZoneKit) to print the
plan for a survey JSON without touching anything:  python unreal_setup.py <survey.json> <TemplateKey>
"""
import json
import os
import re
import sys
import types

CONFIG = None
PATCHER_SOURCE = None

try:
    import unreal
except ImportError:
    unreal = None

GAME = '/Game'
ANIM_CLASSES = ('AnimSequence', 'AnimMontage')
SKIP_SIDE_FOLDERS = ('tp', 'characters', 'zombie', 'skins')
REPORT = []


def log(message):
    REPORT.append(message)
    print(message)
    if unreal is not None:
        unreal.log(f'[Arsenal setup] {message}')


def warn(message):
    REPORT.append('WARNING: ' + message)
    print('WARNING: ' + message)
    if unreal is not None:
        unreal.log_warning(f'[Arsenal setup] {message}')


def token_pattern(tokens):
    parts = '|'.join(re.escape(token) for token in sorted({t.lower() for t in tokens if t}, key=len, reverse=True))
    return re.compile(rf'(?<![a-z0-9])(?:{parts})(?![a-z0-9])', re.IGNORECASE)


def split_package(package):
    parts = package.strip('/').split('/')
    return parts[0], parts[1:-1], parts[-1]


# --- selection -----------------------------------------------------------------------------

def select_assets(assets, config, additive_of=None):
    """Sort the template's first-person assets into what is exported and what is checked out.

    assets: iterable of (package, class_name). additive_of(package) -> True/False/None for sequences.
    """
    anim_pattern = token_pattern(config['anim_tokens'])
    mesh_pattern = token_pattern(config['mesh_tokens'])
    anim_tokens = [t.lower() for t in config['anim_tokens']]
    mesh_tokens = [t.lower() for t in config['mesh_tokens']]
    result = {'sequences': [], 'additive': [], 'montages': [], 'collections': [], 'anim_blueprints': [],
              'skeletal_meshes': [], 'skeletons': [], 'static_meshes': []}

    for package, class_name in sorted(assets):
        if not package.startswith(GAME + '/'):
            continue
        lowered = package.lower()
        _root, folders, name = split_package(lowered)

        if class_name in ANIM_CLASSES:
            if '/animations/player/' not in lowered and '/animations/weapons/' not in lowered:
                continue
            if any(folder in SKIP_SIDE_FOLDERS for folder in folders):
                continue
            words = name.split('_')
            if not (name.startswith('as_') or name.startswith('mg_')) or 'fp' not in words:
                continue
            if not anim_pattern.search(name):
                continue
            if class_name == 'AnimMontage':
                result['montages'].append(package)
            elif additive_of is not None and additive_of(package):
                result['additive'].append(package)
            else:
                result['sequences'].append(package)
        elif 'AnimCollection' in class_name:
            if re.fullmatch(rf'animcollection_fp_(?:{"|".join(map(re.escape, anim_tokens))})', name):
                result['collections'].append(package)
        elif class_name in ('AnimBlueprint',):
            if re.fullmatch(rf'animbp_(?:{"|".join(map(re.escape, anim_tokens))})_fp', name):
                result['anim_blueprints'].append(package)
        elif class_name == 'SkeletalMesh':
            if '/skeletalmeshes/weapons/' in lowered and name in [f'sk_{t}' for t in mesh_tokens]:
                result['skeletal_meshes'].append(package)
        elif class_name == 'Skeleton':
            if '/skeletalmeshes/weapons/' in lowered and name in (
                    [f'skel_{t}' for t in mesh_tokens] + [f'sk_{t}_skeleton' for t in mesh_tokens]):
                result['skeletons'].append(package)
        elif class_name == 'StaticMesh':
            if '/animmesh/' in lowered and '/skins/' not in lowered and '_sm_' in name \
                    and mesh_pattern.search(name):
                result['static_meshes'].append(package)
            elif '/weapons/' in lowered and not any(f in lowered for f in ('/skins/', '/animmesh/', '/old/')) \
                    and 'mag' in name and name.startswith('sm_') and 'half' not in name and 'phantom' not in name \
                    and mesh_pattern.search('/'.join(folders)):
                # Magazine meshes (default, increased/big/twin; full/empty) sit in the weapon's folder, and some
                # (SM_ak_mag_full, SM_ar_ak_bigmag_*) do not carry the weapon token in their own name.
                result['static_meshes'].append(package)
    export_additive_overlays(result)
    return result


def export_additive_overlays(result):
    """Additive overlays (shoot, equip, empty click, offset aim, and the player halves of reload and melee)
    store a full pose and are edited in Blender like any other clip; UE subtracts their reference pose itself.
    Only the *_add idle companions stay unexported: the import script rebuilds them from the exported idle."""
    for package in list(result['additive']):
        if not package.lower().endswith('_add'):
            result['additive'].remove(package)
            result['sequences'].append(package)
    result['sequences'].sort()


def exported(selection, config):
    """Packages exported to FBX for Blender (the template's original names)."""
    packages = list(selection['sequences']) + list(selection['skeletal_meshes']) + list(selection['static_meshes'])
    if config.get('export_additive'):
        packages += selection['additive']
    return packages


def copied(selection):
    """Packages checked out into the mod and renamed."""
    keys = ('sequences', 'additive', 'montages', 'collections', 'anim_blueprints', 'skeletons', 'skeletal_meshes')
    return [package for key in keys for package in selection[key]]


# --- naming ----------------------------------------------------------------------------------

def renamed(package, config):
    """The new name of a template package: every template token in folder and asset names becomes the weapon."""
    pattern = token_pattern(list(config['anim_tokens']) + list(config['mesh_tokens']))
    return pattern.sub(config['weapon'], package)


def mod_package(package, mod):
    return f'/{mod}' + package[len(GAME):]


def export_file(package, export_dir):
    return os.path.join(export_dir, *package[len(GAME) + 1:].split('/')) + '.fbx'


def build_plan(assets, config, additive_of=None):
    selection = select_assets(assets, config, additive_of)
    for package in config.get('attachment_meshes', []):
        if package not in selection['static_meshes']:
            selection['static_meshes'].append(package)
    plan = {'selection': selection, 'exports': [], 'copies': []}
    for package in exported(selection, config):
        plan['exports'].append((package, export_file(package, config['export_dir'])))
    for package in copied(selection):
        source = mod_package(package, config['mod'])
        plan['copies'].append((package, source, renamed(source, config)))
    names = [target for _package, _source, target in plan['copies']]
    clashes = {name for name in names if names.count(name) > 1}
    if clashes:
        raise RuntimeError(f'Renaming would give two assets the same name: {sorted(clashes)[:5]}')
    return plan


# --- ZoneKit side ----------------------------------------------------------------------------

def registry_assets():
    registry = unreal.AssetRegistryHelpers.get_asset_registry()
    if registry.is_loading_assets():
        warn('The asset registry is still loading; run the script again when it finishes.')
    assets = []
    for data in registry.get_all_assets():
        package = str(data.get_editor_property('package_name'))
        if package.startswith(GAME + '/'):
            path = getattr(data, 'asset_class_path', None)
            class_name = str(path.asset_name) if path is not None else str(data.get_editor_property('asset_class'))
            assets.append((package, class_name))
    return registry, assets


def sequence_is_additive(package):
    asset = unreal.EditorAssetLibrary.load_asset(package)
    if asset is not None:
        try:
            found = re.search(r'AAT_\w+', str(asset.get_editor_property('additive_anim_type')))
            if found:
                return found.group(0) != 'AAT_NONE'
        except Exception:
            pass
    lowered = package.lower()
    return '_add' in lowered.rsplit('/', 1)[-1] or '/additive' in lowered


def nanite_fallback_off(asset):
    """Nanite meshes export their reduced fallback mesh; with Nanite off for the export the full source LOD0 is used.

    Returns a function that restores the setting (nothing is saved to disk)."""
    try:
        subsystem = unreal.get_editor_subsystem(unreal.StaticMeshEditorSubsystem)
        settings = subsystem.get_nanite_settings(asset)
        if not settings.enabled:
            return None
        settings.enabled = False
        subsystem.set_nanite_settings(asset, settings, True)
    except Exception as error:
        warn(f'Could not turn Nanite off to export the full-detail mesh of {asset.get_name()}: {error}')
        return None

    def restore():
        try:
            settings.enabled = True
            subsystem.set_nanite_settings(asset, settings, True)
        except Exception as error:
            warn(f'Could not turn Nanite back on for {asset.get_name()} (do not save it): {error}')
    return restore


def export_package(package, filename, is_mesh):
    asset = unreal.EditorAssetLibrary.load_asset(package)
    if asset is None:
        raise RuntimeError('could not load the asset')
    os.makedirs(os.path.dirname(filename), exist_ok=True)
    options = unreal.FbxExportOption()
    # Only the full-detail LOD0; lower LODs just add SK_stalker_LOD1 style extras in Blender.
    try:
        options.set_editor_property('level_of_detail', False)
    except Exception:
        pass
    if not is_mesh:
        # Blender takes the headless character mesh from the animation FBX itself.
        try:
            options.set_editor_property('export_preview_mesh', True)
        except Exception as error:
            warn(f'Could not enable "Export Preview Mesh": {error}')
    task = unreal.AssetExportTask()
    task.set_editor_property('object', asset)
    task.set_editor_property('filename', filename)
    task.set_editor_property('automated', True)
    task.set_editor_property('prompt', False)
    task.set_editor_property('replace_identical', True)
    task.set_editor_property('options', options)
    restore = nanite_fallback_off(asset) if isinstance(asset, unreal.StaticMesh) else None
    try:
        exported_ok = unreal.Exporter.run_asset_export_task(task)
    finally:
        if restore:
            restore()
    if not exported_ok or not os.path.isfile(filename):
        raise RuntimeError('the export produced no file')


def run_exports(plan, config):
    done = failed = 0
    for package, filename in plan['exports']:
        is_mesh = package in plan['selection']['static_meshes'] or package in plan['selection']['skeletal_meshes']
        try:
            export_package(package, filename, is_mesh)
            done += 1
        except Exception as error:
            failed += 1
            warn(f'Export failed for {package}: {error}')
    log(f'Exported {done} files to {config["export_dir"]} ({failed} failed)')
    return done, failed


def _vector(value, names):
    return [float(getattr(value, name)) for name in names]


def export_sockets(plan, config):
    """Write the weapon mesh's sockets (silencer, laser...) so Blender can place attachments where the game does."""
    entries = []
    seen = set()
    for package in plan['selection']['skeletal_meshes']:
        mesh = unreal.EditorAssetLibrary.load_asset(package)
        owners = [mesh]
        try:
            owners.append(mesh.get_editor_property('skeleton'))
        except Exception:
            pass
        for owner in owners:
            if owner is None:
                continue
            found = []
            for prop in ('sockets', 'mesh_only_socket_list'):
                try:
                    found += list(owner.get_editor_property(prop) or [])
                except Exception:
                    pass
            for name in ('SilencerMuzzleSocket', 'LaserSocket'):
                finder = getattr(owner, 'find_socket', None)
                if finder:
                    try:
                        socket = finder(name)
                        if socket:
                            found.append(socket)
                    except Exception:
                        pass
            for socket in found:
                try:
                    name = str(socket.get_editor_property('socket_name'))
                    if name in seen:
                        continue
                    seen.add(name)
                    entries.append({
                        'name': name,
                        'bone': str(socket.get_editor_property('bone_name')),
                        'location': _vector(socket.get_editor_property('relative_location'), 'xyz'),
                        'rotation': _vector(socket.get_editor_property('relative_rotation'), ('roll', 'pitch', 'yaw')),
                        'scale': _vector(socket.get_editor_property('relative_scale'), 'xyz'),
                    })
                except Exception as error:
                    warn(f'Could not read a socket of {package}: {error}')
        if not entries:
            names = [n for n in dir(mesh) if 'socket' in n.lower()]
            warn(f'No sockets could be read from {package} (socket-related attributes: {names})')
    path = os.path.join(config['export_dir'], 'weapon_sockets.json')
    with open(path, 'w', encoding='utf-8') as handle:
        json.dump(entries, handle, indent=2)
    log(f'Wrote {len(entries)} sockets to {path}')


def _material_slots(asset):
    for prop in ('static_materials', 'materials'):
        try:
            slots = asset.get_editor_property(prop)
        except Exception:
            continue
        return [slot.get_editor_property('material_interface') for slot in slots]
    return []


def _material_textures(material):
    """{parameter name: texture asset} of a material instance, nearest instance first, then its parents."""
    textures = {}
    guard = 0
    while material is not None and guard < 8:
        guard += 1
        try:
            values = material.get_editor_property('texture_parameter_values')
        except Exception:
            break
        for value in values:
            name = str(value.get_editor_property('parameter_info').get_editor_property('name'))
            texture = value.get_editor_property('parameter_value')
            if texture is not None and name not in textures:
                textures[name] = texture
        try:
            material = material.get_editor_property('parent')
        except Exception:
            break
    return textures


def export_textures(plan, config):
    """Export every texture used by the exported meshes' materials, with materials.json naming them."""
    library = unreal.EditorAssetLibrary
    textures_dir = os.path.join(config['export_dir'], 'Textures')
    os.makedirs(textures_dir, exist_ok=True)
    materials = {}
    files = {}
    selection = plan['selection']
    for package in list(selection['skeletal_meshes']) + list(selection['static_meshes']):
        asset = library.load_asset(package)
        for material in _material_slots(asset) if asset else []:
            if material is None or material.get_name() in materials:
                continue
            entry = {}
            for parameter, texture in _material_textures(material).items():
                name = texture.get_name()
                if name not in files:
                    target = os.path.join(textures_dir, name + '.png')
                    task = unreal.AssetExportTask()
                    task.set_editor_property('object', texture)
                    task.set_editor_property('filename', target)
                    task.set_editor_property('automated', True)
                    task.set_editor_property('prompt', False)
                    task.set_editor_property('replace_identical', True)
                    try:
                        ok = unreal.Exporter.run_asset_export_task(task) and os.path.isfile(target)
                    except Exception as error:
                        warn(f'Texture export failed for {name}: {error}')
                        ok = False
                    files[name] = f'Textures/{name}.png' if ok else None
                if files[name]:
                    entry[parameter] = files[name]
            materials[material.get_name()] = entry
    with open(os.path.join(config['export_dir'], 'materials.json'), 'w', encoding='utf-8') as handle:
        json.dump(materials, handle, indent=2)
    log(f'Exported {sum(1 for f in files.values() if f)} textures for {len(materials)} materials')


def checkout_copies(plan, config):
    library = unreal.EditorAssetLibrary
    ready = []
    for package, source, target in plan['copies']:
        if not library.does_asset_exist(source):
            try:
                library.checkout_asset(package)
            except Exception as error:
                warn(f'Checkout failed for {package}: {error}')
        if not library.does_asset_exist(source):
            warn(f'{package} is not in the mod after checkout (expected {source}); copying it instead')
            try:
                library.duplicate_asset(package, source)
            except Exception as error:
                warn(f'Copy failed for {package}: {error}')
        if library.does_asset_exist(source):
            ready.append((package, source, target))
        else:
            warn(f'Skipping {package}: no copy in the mod')
    return ready


def run_rename(items):
    tools = unreal.AssetToolsHelpers.get_asset_tools()
    library = unreal.EditorAssetLibrary
    data = []
    for _package, source, target in items:
        if source == target:
            continue
        asset = library.load_asset(source)
        if asset is None:
            warn(f'Cannot load {source} to rename it')
            continue
        folder, name = target.rsplit('/', 1)
        data.append(unreal.AssetRenameData(asset, folder, name))
    if data and not tools.rename_assets(data):
        warn('rename_assets reported a failure; check the output log')
    return len(data)


def load_patcher():
    """The uasset patcher: embedded in this script by the add-on, or imported next to it when run offline."""
    if PATCHER_SOURCE:
        module = types.ModuleType('uasset_patch')
        exec(compile(PATCHER_SOURCE, 'uasset_patch', 'exec'), module.__dict__)
        return module
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import uasset_patch
    return uasset_patch


REFERENCE_KINDS = ('sequences', 'additive', 'montages', 'collections', 'anim_blueprints', 'skeletal_meshes')


def montage_name_mapping(plan):
    """{old name: new name} for the name-table strings that spell a copied template asset (sequence, montage,
    collection, AnimBP, skeletal mesh): its /Game package path, its pre-rename mod path, and its bare asset name.
    Skeletons are left out: every copy keeps using the template skeleton, which the mod's skeletal mesh already
    uses. Ambiguous bare names are left out."""
    selection = plan['selection']
    wanted = {package for key in REFERENCE_KINDS for package in selection[key]}
    mapping = {}
    leaves = {}
    for package, source, target in plan['copies']:
        if package not in wanted:
            continue
        mapping[package] = target
        mapping[source] = target
        old_leaf, new_leaf = package.rsplit('/', 1)[1], target.rsplit('/', 1)[1]
        leaves.setdefault(old_leaf, set()).add(new_leaf)
    for old_leaf, new_leaves in leaves.items():
        if len(new_leaves) == 1 and old_leaf not in new_leaves:
            mapping[old_leaf] = next(iter(new_leaves))
        elif len(new_leaves) > 1:
            warn(f'{old_leaf} would be renamed to several names; left alone: {sorted(new_leaves)}')
    mapping.pop('', None)
    return {old: new for old, new in mapping.items() if old != new}


def mod_file(package, mod):
    folder = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir()), 'Mods', mod, 'Content')
    return os.path.join(folder, *package[len(mod) + 2:].split('/')) + '.uasset'


def reload_packages(assets):
    mode = getattr(unreal.ReloadPackagesInteractionMode, 'ASSUME_POSITIVE')
    return unreal.EditorLoadingAndSavingUtils.reload_packages([asset.get_package() for asset in assets], mode)


def patch_references(plan, config):
    """Point every copied asset at the other copies instead of the /Game originals, by rewriting names in the
    mod's own .uasset headers.

    Copies made with checkout/duplicate keep referencing the template: a montage still plays the template's
    sequences, the AnimCollection lists the template's montages and the AnimBP loads the template's collection, so
    none of the weapon's new animations are ever used. Python cannot edit montage slot data and consolidate_assets
    on /Game assets crashes ZoneKit, but all of these references live in the import table, so renaming them on
    disk keeps slots, sections, notifies and graphs exactly as they were. The mod's files only; /Game is never
    touched. Originals are kept in <export folder>/reference_backups."""
    library = unreal.EditorAssetLibrary
    patcher = load_patcher()
    mapping = montage_name_mapping(plan)
    backups = os.path.join(config['export_dir'], 'reference_backups')
    wanted = {package for key in REFERENCE_KINDS for package in plan['selection'][key]}
    patched, failed, unchanged = [], 0, 0
    for package, _source, target in plan['copies']:
        if package not in wanted:
            continue
        path = mod_file(target, config['mod'])
        try:
            if not patcher.patch_file(path, mapping, write=False):
                unchanged += 1
                continue
        except (patcher.PatchError, OSError) as error:
            failed += 1
            warn(f'Cannot patch {target}: {error}')
            continue
        asset = library.load_asset(target)
        if asset is None:
            warn(f'Cannot load {target} to patch it')
            failed += 1
            continue
        try:
            # A loaded package keeps its file open; a forced save releases it before the file is rewritten.
            library.save_loaded_asset(asset, False)
            patcher.patch_file(path, mapping, backup_dir=backups)
            patched.append(asset)
        except (patcher.PatchError, OSError) as error:
            failed += 1
            warn(f'Could not patch {target}: {error}')
    if patched:
        try:
            reload_packages(patched)
        except Exception as error:
            failed += len(patched)
            warn(f'Patched {len(patched)} files but could not reload them ({error}). Close and reopen ZoneKit '
                 'so they load from disk, and do not save them before then.')
    log(f'Repointed {len(patched)} copied assets at the renamed copies ({unchanged} needed nothing, {failed} failed)')
    return failed


def check_montages(plan, config):
    """Mod montages that still play a /Game template animation after patching."""
    library = unreal.EditorAssetLibrary
    stale = 0
    for package, _source, target in plan['copies']:
        if package not in plan['selection']['montages']:
            continue
        montage = library.load_asset(target)
        reference = montage.get_first_anim_reference() if montage else None
        if reference is not None and reference.get_path_name().startswith(GAME + '/'):
            stale += 1
            warn(f'{target} still plays the template animation {reference.get_name()}')
    log(f'{stale} montages still play a template animation' if stale else 'All montages play mod animations')
    return stale

def tidy_redirectors(items, registry, mod):
    library = unreal.EditorAssetLibrary
    removed = 0
    for _package, source, target in items:
        if source == target or not library.does_asset_exist(source):
            continue
        datas = registry.get_assets_by_package_name(source)
        if not datas or 'ObjectRedirector' not in str(datas[0].get_editor_property('asset_class_path')):
            continue
        if registry.get_referencers(source, unreal.AssetRegistryDependencyOptions()):
            continue
        if library.delete_asset(source):
            removed += 1
    folders = sorted({source.rsplit('/', 1)[0] for _p, source, _t in items}, key=len, reverse=True)
    for folder in folders:
        if library.does_directory_exist(folder) and not library.does_directory_have_assets(folder, True):
            library.delete_directory(folder)
    return removed


def check_references(items, registry, config):
    """Mod copies that still point at a /Game template asset that has a mod copy (so the rename missed them)."""
    originals = {package for package, _s, _t in items}
    options = unreal.AssetRegistryDependencyOptions()
    for name in ('include_soft_package_references', 'include_hard_package_references'):
        try:
            options.set_editor_property(name, True)
        except Exception:
            pass
    problems = 0
    for _package, _source, target in items:
        for dependency in registry.get_dependencies(target.rsplit('.', 1)[0], options) or []:
            dependency = str(dependency)
            if dependency in originals:
                problems += 1
                warn(f'{target} still references the template asset {dependency}')
    return problems


def write_report(config, plan, extra):
    folder = config['export_dir']
    os.makedirs(folder, exist_ok=True)
    selection = plan['selection']
    lines = [f'Arsenal ZoneKit setup for "{config["weapon"]}" from {config["template"]} (mod {config["mod"]})', '']
    for key, packages in selection.items():
        lines.append(f'{key}: {len(packages)}')
    lines += ['', 'EXPORT']
    lines += [f'  {package} -> {filename}' for package, filename in plan['exports']]
    lines += ['', 'CHECKOUT + RENAME']
    lines += [f'  {source} -> {target}' for _p, source, target in plan['copies']]
    lines += ['', 'LOG'] + REPORT
    path = os.path.join(folder, f'zonekit_setup_{config["weapon"]}_report.txt')
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines) + '\n')
    log(f'Report written to {path}')


def load_config():
    if CONFIG:
        return CONFIG
    raise RuntimeError('This script has no settings; generate it from the Arsenal "1. Set Up" panel.')


def validate(config):
    if not re.fullmatch(r'[a-z0-9]+', config['weapon']):
        raise RuntimeError(f'Weapon name "{config["weapon"]}" must be lower-case letters and digits only.')
    if not re.fullmatch(r'[A-Za-z0-9_]+', config['mod']):
        raise RuntimeError(f'Mod name "{config["mod"]}" is not valid.')


def _main():
    config = load_config()
    validate(config)
    if unreal is None:
        raise RuntimeError('Run this script inside ZoneKit (it needs the unreal module).')
    registry, assets = registry_assets()
    additive_of = sequence_is_additive
    plan = build_plan(assets, config, additive_of)
    selection = plan['selection']
    log(f'Template {config["template"]}: ' + ', '.join(f'{len(v)} {k}' for k, v in selection.items()))
    if not selection['sequences'] or not selection['skeletal_meshes']:
        raise RuntimeError('The template has no first-person sequences or no skeletal mesh; nothing done.')
    if config.get('dry_run'):
        log('Dry run: nothing exported, checked out or renamed.')
        write_report(config, plan, {})
        return
    if config.get('export', True):
        run_exports(plan, config)
        for step in (export_sockets, export_textures):
            try:
                step(plan, config)
            except Exception as error:
                warn(f'{step.__name__} failed: {error}')
    if config.get('checkout', True):
        library = unreal.EditorAssetLibrary
        if library.does_directory_exist(f'/{config["mod"]}') is False:
            raise RuntimeError(f'The mod /{config["mod"]} does not exist in this ZoneKit project.')
        items = checkout_copies(plan, config)
        log(f'{len(items)} assets are in the mod; renaming to "{config["weapon"]}"')
        count = run_rename(items)
        log(f'Renamed {count} assets')
        if config.get('patch_references', True):
            patch_references(plan, config)
        check_montages(plan, config)
        removed = tidy_redirectors(items, registry, config['mod'])
        problems = check_references(items, registry, config)
        if removed:
            log(f'Removed {removed} redirectors')
        library.save_directory(f'/{config["mod"]}', only_if_is_dirty=True, recursive=True)
        log(f'{problems} copies still reference a template asset' if problems else 'No stale references to template assets')
    write_report(config, plan, {})
    log('Setup finished. Next: in Blender, press Import Weapon with the ZoneKit export folder.')


def notify_completion(error=None):
    warnings = sum(line.startswith('WARNING: ') for line in REPORT)
    status = 'failed' if error is not None else 'finished with warnings' if warnings else 'complete'
    message = str(error) if error is not None else (
        f'{warnings} warnings. See the Output Log and setup report for details.' if warnings
        else 'Setup finished. Next: in Blender, press Import Weapon.')
    if CONFIG and CONFIG.get('dry_run') and error is None:
        message = 'Dry run finished; no assets were changed. See the setup report for details.'
    if unreal is not None:
        category = (unreal.AppMsgCategory.ERROR if error is not None else
                    unreal.AppMsgCategory.WARNING if warnings else unreal.AppMsgCategory.INFO)
        unreal.EditorDialog.show_message(
            f'Arsenal setup {status}', message, unreal.AppMsgType.OK, message_category=category)


def main():
    REPORT.clear()
    try:
        _main()
    except Exception as error:
        if unreal is not None:
            unreal.log_error(f'Arsenal setup failed: {error}')
            notify_completion(error)
        raise
    else:
        notify_completion()


def offline(survey_path, key):
    with open(survey_path, encoding='utf-8') as handle:
        data = json.load(handle)[key]
    assets = [(r['package'], r['class']) for r in data['assets']]
    additive = {r['package']: r.get('details', {}).get('additive', '') not in ('', 'AAT_NONE') for r in data['assets']}
    config = {'template': key, 'weapon': 'newgun', 'mod': 'TestMod', 'export_dir': 'EXPORT',
              'anim_tokens': OFFLINE_TOKENS[key][0], 'mesh_tokens': OFFLINE_TOKENS[key][1]}
    plan = build_plan(assets, config, lambda package: additive.get(package, False))
    for name, packages in plan['selection'].items():
        print(f'{name}: {len(packages)}')
    for _package, source, target in plan['copies']:
        print(f'  {source} -> {target}')


