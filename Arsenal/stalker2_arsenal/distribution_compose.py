"""Self-contained mod-wide distribution composer embedded in generated ZoneKit scripts."""
import copy
import json
import math
import os
import re
import tempfile


HEADER = '// Generated by Arsenal.'
RANKS = ('Newbie', 'Experienced', 'Veteran', 'Master')
DIFFICULTIES = ('Easy', 'Medium', 'Hard', 'Stalker')


def parse(text):
    """Parse only the CFG subset written by Arsenal; keep wildcard and patch operations."""
    root = []
    stack = [root]
    for number, line in enumerate(text.splitlines(), 1):
        line = line.split('//', 1)[0].strip()
        if not line:
            continue
        begin = re.fullmatch(r'(\w+|\[\d+\]|\[\*\])\s*:\s*struct.begin(?:\s+\{([^{}]+)\})?', line)
        if begin:
            child = []
            stack[-1].append((begin[1], child, begin[2] or ''))
            stack.append(child)
        elif line == 'struct.end' and len(stack) > 1:
            stack.pop()
        elif re.fullmatch(r'\[\d+\]\s*:\s*removenode', line):
            stack[-1].append((line.split(':', 1)[0].strip(), None, 'remove'))
        elif re.fullmatch(r'\w+\s*=.+', line):
            key, value = line.split('=', 1)
            stack[-1].append((key.strip(), value.strip(), 'value'))
        else:
            raise RuntimeError(f'Unsupported Arsenal distribution CFG at line {number}: {line}')
    if len(stack) != 1:
        raise RuntimeError('Unclosed Arsenal distribution CFG block.')
    return root


def apply(target, nodes):
    for key, value, option in nodes:
        if key == '[*]':
            indices = [int(k[1:-1]) for k in target if re.fullmatch(r'\[\d+\]', k)]
            key = f'[{max(indices, default=-1) + 1}]'
        if option == 'remove':
            if key not in target:
                raise RuntimeError(f'Distribution removal target does not exist: {key}')
            del target[key]
        elif option == 'value':
            target[key] = value
        else:
            if option == 'bpatch' and key not in target:
                raise RuntimeError(f'Distribution patch target does not exist: {key}')
            child = target[key] if option == 'bpatch' else {}
            apply(child, value)
            target[key] = child
    return target


def children(nodes, key):
    matches = [value for name, value, option in nodes if name == key and isinstance(value, list)]
    if len(matches) != 1:
        raise RuntimeError(f'Expected one distribution block: {key}')
    return matches[0]


def identifier(value):
    if not isinstance(value, str) or not re.fullmatch(r'[A-Za-z0-9_]+', value):
        raise RuntimeError(f'Invalid distribution identifier: {value!r}')
    return value


def record_from_text(mod, weapon, text, defaults, sid=None):
    """Migrate the old generated CFG or build the same structured plan for a fresh export."""
    identifier(mod)
    identifier(weapon)
    nodes = parse(text)
    private = {}
    patches = []
    for name, value, option in nodes:
        if option == 'bpatch':
            patches.append((name, value))
        elif name.startswith(f'Arsenal_{mod}_{weapon}_') and option == (
                'refurl=@BaseGame/ItemGeneratorPrototypes.cfg;refkey=[0]'):
            if name in private:
                raise RuntimeError(f'Duplicate private distribution generator: {name}')
            private[name] = apply({}, value)
        else:
            raise RuntimeError(f'Unrecognized generated distribution definition: {name}')
    operations = []
    candidates = set()
    used_private = set()
    for root, patch in patches:
        kind = 'npc' if root in defaults['npc'] else 'trader'
        table = defaults['npc'] if kind == 'npc' else defaults['traders']
        if root not in table or len(patch) != 1:
            raise RuntimeError(f'Unsupported distribution patch: {root}')
        base_groups = table[root]['groups']
        group_nodes = children(patch, 'ItemGenerator')
        index = 0
        while index < len(group_nodes):
            key, value, option = group_nodes[index]
            if key not in base_groups:
                raise RuntimeError(f'Unknown source distribution group: {root}/{key}')
            base = copy.deepcopy(base_groups[key])
            index += 1
            if option == 'remove':
                variants = {}
                while index < len(group_nodes) and group_nodes[index][0] == '[*]':
                    _, row, row_option = group_nodes[index]
                    if row_option:
                        raise RuntimeError(f'Unsupported replacement group: {root}/{key}')
                    variants[f'[{len(variants)}]'] = apply({}, row)
                    index += 1
                if not variants:
                    raise RuntimeError(f'No replacement for distribution group: {root}/{key}')
                operations.append(dict(root=root, group=key, route=None, kind=kind,
                                       base={'[0]': base}, variants=variants))
            elif option == 'bpatch':
                item_nodes = children(value, 'PossibleItems')
                if len(value) != 1:
                    raise RuntimeError(f'Unsupported group patch: {root}/{key}')
                if item_nodes and all(item_option == 'bpatch' for _, _, item_option in item_nodes):
                    for item_key, fields, _ in item_nodes:
                        if len(fields) != 1 or fields[0][0] != 'ItemGeneratorPrototypeSID':
                            raise RuntimeError(f'Unsupported route patch: {root}/{key}/{item_key}')
                        custom = fields[0][1]
                        if custom not in private:
                            raise RuntimeError(f'Missing private distribution generator: {custom}')
                        used_private.add(custom)
                        donor = base['PossibleItems'][item_key]['ItemGeneratorPrototypeSID']
                        pools = defaults['pistols'] if kind == 'npc' else defaults['trade_pools']
                        operations.append(dict(
                            root=root, group=key, route=item_key, kind=kind,
                            base=copy.deepcopy(pools[donor]),
                            variants=copy.deepcopy(private[custom]['ItemGenerator'])))
                else:
                    variant = apply(copy.deepcopy(base), value)
                    operations.append(dict(root=root, group=key, route=None, kind=kind,
                                           base={'[0]': base}, variants={'[0]': variant}))
            else:
                raise RuntimeError(f'Unsupported source group operation: {root}/{key}')
    if used_private != set(private):
        raise RuntimeError('Unreferenced private distribution generators; regenerate this weapon.')
    for operation in operations:
        base_sids = {item.get('ItemPrototypeSID') for group in operation['base'].values()
                     for item in group['PossibleItems'].values()}
        candidates.update(item['ItemPrototypeSID'] for group in operation['variants'].values()
                          for item in group['PossibleItems'].values()
                          if 'ItemPrototypeSID' in item and item['ItemPrototypeSID'] not in base_sids)
    if sid is None and len(candidates) == 1:
        sid = candidates.pop()
    if operations and (not sid or candidates - {sid}):
        raise RuntimeError(f'Cannot identify the weapon in {weapon} distribution; regenerate its export.')
    return dict(version=1, mod=mod, weapon=weapon, sid=sid, operations=operations)


def filters(group, key, values, prefix):
    result = [value.strip().removeprefix(prefix) for value in group.get(
        key, ','.join(prefix + value for value in values)).split(',')]
    if not result or any(value not in values for value in result):
        raise RuntimeError(f'Unsupported distribution filter {key}: {result}')
    return result


def finite_number(value):
    result = float(value.rstrip('f'))
    if not math.isfinite(result) or result < 0:
        raise RuntimeError(f'Invalid distribution weight: {value}')
    return result


def npc_groups(plans, label, warn):
    base = plans[0][1]['base']
    result = {}
    for source in base.values():
        rows = []
        for rank in filters(source, 'PlayerRank', RANKS, 'ERank::'):
            for difficulty in filters(source, 'Diff', DIFFICULTIES, 'EGameDifficulty::'):
                additions = []
                original_items = source['PossibleItems']
                total = math.fsum(finite_number(item.get('Weight', '4.f'))
                                  for item in original_items.values())
                for record, operation in plans:
                    matching = [group for group in operation['variants'].values()
                                if rank in filters(group, 'PlayerRank', RANKS, 'ERank::')
                                and difficulty in filters(group, 'Diff', DIFFICULTIES, 'EGameDifficulty::')
                                and {k: v for k, v in group.items()
                                     if k not in ('PlayerRank', 'Diff', 'PossibleItems')} == {
                                         k: v for k, v in source.items()
                                         if k not in ('PlayerRank', 'Diff', 'PossibleItems')}]
                    # Several source groups can have identical filters; match the retained vanilla pool.
                    matching = [group for group in matching if
                                {k: v for k, v in group['PossibleItems'].items()
                                 if v.get('ItemPrototypeSID') != record['sid']} == original_items
                                or all(item.get('ItemPrototypeSID') == record['sid']
                                       for item in group['PossibleItems'].values())]
                    if len(matching) != 1:
                        raise RuntimeError(f'Ambiguous NPC pool in {label}, {rank}/{difficulty}; '
                                           f'regenerate {record["weapon"]}.')
                    items = matching[0]['PossibleItems']
                    ours = [item for item in items.values() if item.get('ItemPrototypeSID') == record['sid']]
                    if not ours:
                        continue
                    if len(ours) != 1 or 'Chance' in ours[0]:
                        raise RuntimeError(f'Unsupported NPC candidate in {label}.')
                    weight = finite_number(ours[0]['Weight'])
                    share = 1 if len(items) == 1 else weight / (total + weight)
                    additions.append((record['weapon'], copy.deepcopy(ours[0]), share))
                share_sum = math.fsum(row[2] for row in additions)
                if share_sum > 1 + 1e-10:
                    weapons = ', '.join(f'{name} ({share:.2%})' for name, _, share in additions)
                    effective = ', '.join(f'{name} ({share / share_sum:.2%})'
                                          for name, _, share in additions)
                    warn(f'Combined NPC share exceeds 100% in {label}, {rank}/{difficulty}: '
                         f'{weapons}. Automatically scaled proportionally to 100%: {effective}.')
                    additions = [(name, item, share / share_sum) for name, item, share in additions]
                    share_sum = 1.0
                row = copy.deepcopy(source)
                row['PlayerRank'] = f'ERank::{rank}'
                row['Diff'] = f'EGameDifficulty::{difficulty}'
                if share_sum >= 1 - 1e-10:
                    row['PossibleItems'] = {}
                elif additions and total <= 0:
                    raise RuntimeError(f'Empty vanilla weight in {label}.')
                for _, item, share in additions:
                    weight = share if share_sum >= 1 - 1e-10 else total * share / (1 - share_sum)
                    item['Weight'] = format(weight, '.12g')
                    append_item(row['PossibleItems'], item)
                rows.append(row)
        # Combine identical difficulty variants, retaining each rank's independent selection.
        combined = {}
        for row in rows:
            marker = json.dumps({k: v for k, v in row.items() if k != 'Diff'}, sort_keys=True)
            if marker in combined:
                combined[marker]['Diff'] += ', ' + row['Diff']
            else:
                combined[marker] = row
        for row in combined.values():
            result[f'[{len(result)}]'] = row
    return result


def append_item(items, item):
    index = max((int(key[1:-1]) for key in items), default=-1) + 1
    items[f'[{index}]'] = item


def trader_groups(plans, label):
    result = copy.deepcopy(plans[0][1]['base'])
    for record, operation in plans:
        if set(operation['variants']) != set(result):
            raise RuntimeError(f'Unexpected trader pool structure: {label}')
        for key, source in operation['base'].items():
            variant = operation['variants'][key]
            additions = [item for item in variant['PossibleItems'].values()
                         if item.get('ItemPrototypeSID') == record['sid']]
            retained = {k: v for k, v in variant['PossibleItems'].items()
                        if v.get('ItemPrototypeSID') != record['sid']}
            if retained != source['PossibleItems'] or {
                    k: v for k, v in variant.items() if k != 'PossibleItems'} != {
                        k: v for k, v in source.items() if k != 'PossibleItems'}:
                raise RuntimeError(f'Unexpected trader changes: {label}')
            for item in additions:
                append_item(result[key]['PossibleItems'], copy.deepcopy(item))
    return result


def emit(name, fields, option='', depth=0):
    indent = '   ' * depth
    lines = [f'{indent}{name} : struct.begin' + (f' {{{option}}}' if option else '')]
    for key, value in fields.items():
        if isinstance(value, dict):
            lines.extend(emit(key, value, depth=depth + 1))
        else:
            lines.append(f'{indent}   {key} = {value}')
    lines.append(f'{indent}struct.end')
    return lines


def compose(records, warn=print):
    records = json.loads(json.dumps(records, sort_keys=True, allow_nan=False))
    plans = {}
    mod = None
    seen_sids = set()
    for record in sorted(records, key=lambda row: row['weapon']):
        if record.get('version') != 1:
            raise RuntimeError('Unsupported Arsenal distribution record version.')
        identifier(record['weapon'])
        identifier(record['mod'])
        if mod is not None and mod != record['mod']:
            raise RuntimeError('Distribution records belong to different mods.')
        mod = record['mod']
        if record['sid']:
            identifier(record['sid'])
            if record['sid'] in seen_sids:
                raise RuntimeError(f'Duplicate weapon distribution SID: {record["sid"]}')
            seen_sids.add(record['sid'])
        for operation in record['operations']:
            key = (operation['root'], operation['group'], operation['route'] or '')
            plans.setdefault(key, []).append((record, operation))
    patches = {}
    private = []
    for (root, group, route), entries in sorted(plans.items()):
        operation = entries[0][1]
        if any(row['base'] != operation['base'] or row['kind'] != operation['kind']
               for _, row in entries):
            raise RuntimeError(f'Incompatible distribution baselines in {root}/{group}; '
                               'regenerate affected exports with the same add-on version.')
        label = f'{root}/{group}/{route}'
        groups = npc_groups(entries, label, warn) if operation['kind'] == 'npc' else trader_groups(entries, label)
        root_patch = patches.setdefault(root, [])
        if route:
            custom = f'Arsenal_{mod}_Combined_{root}_{group[1:-1]}_{route[1:-1]}'
            private.extend(emit(custom, {'SID': custom, 'ItemGenerator': groups},
                                'refurl=@BaseGame/ItemGeneratorPrototypes.cfg;refkey=[0]'))
            private.append('')
            values = {'PossibleItems': {route: {'ItemGeneratorPrototypeSID': custom}}}
            root_patch.append((group, values, True))
        elif operation['kind'] == 'npc':
            root_patch.append((group, groups, False))
        else:
            original = operation['base']['[0]']['PossibleItems']
            additions = [item for key, item in groups['[0]']['PossibleItems'].items() if key not in original]
            root_patch.append((group, additions, True))
    attachment_plans = {}
    attachment_routes = {}
    for record in sorted(records, key=lambda row: row['weapon']):
        for addition in record.get('trader_attachments', []):
            root, group = identifier(addition['root']), addition['group']
            if group is not None and not re.fullmatch(r'\[\d+\]', group):
                raise RuntimeError(f'Invalid attachment stock group: {group}')
            if root in attachment_routes and attachment_routes[root] != group:
                raise RuntimeError(f'Incompatible attachment stock routes in {root}; regenerate exports.')
            attachment_routes[root] = group
            key = (root, group)
            plan = attachment_plans.setdefault(key, {'base': addition['base'], 'items': []})
            if plan['base'] != addition['base']:
                raise RuntimeError(f'Incompatible attachment stock baselines in {root}; regenerate exports.')
            for item in addition['items']:
                identifier(item['ItemPrototypeSID'])
                if any(old['ItemPrototypeSID'] == item['ItemPrototypeSID'] for old in plan['items']):
                    raise RuntimeError(f'Duplicate attachment stock SID in {root}: {item["ItemPrototypeSID"]}')
                plan['items'].append(item)
    new_attachment_groups = {}
    for (root, group), plan in sorted(attachment_plans.items(), key=lambda row: (row[0][0], row[0][1] or '')):
        if group is None:
            new_attachment_groups[root] = {
                'Category': 'EItemGenerationCategory::Attach',
                'PlayerRank': ', '.join(f'ERank::{rank}' for rank in RANKS),
                'bAllowSameCategoryGeneration': 'true',
                'PossibleItems': {f'[{index}]': item for index, item in enumerate(plan['items'])},
            }
            patches.setdefault(root, [])
        else:
            patches.setdefault(root, []).append((group, plan['items'], True))
    lines = [HEADER + ' Combined mod distribution; do not edit.', ''] + private
    for root, operations in sorted(patches.items()):
        lines += [f'{root} : struct.begin {{bpatch}}', '   ItemGenerator : struct.begin {bpatch}']
        # Several routes in one group must also share a single patch block.
        grouped = {}
        for group, values, patch in operations:
            grouped.setdefault(group, []).append((values, patch))
        for group, rows in grouped.items():
            if any(not patch for _, patch in rows):
                if len(rows) != 1:
                    raise RuntimeError(f'Overlapping direct and route distribution patches: {root}/{group}')
                lines.append(f'      {group} : removenode')
                for row in rows[0][0].values():
                    lines.extend(emit('[*]', row, depth=2))
                continue
            lines += [f'      {group} : struct.begin {{bpatch}}',
                      '         PossibleItems : struct.begin {bpatch}']
            for values, _ in rows:
                if isinstance(values, dict):
                    for route, fields in values['PossibleItems'].items():
                        lines.extend(emit(route, fields, 'bpatch', 4))
                else:
                    for item in values:
                        lines.extend(emit('[*]', item, depth=4))
            lines += ['         struct.end', '      struct.end']
        if root in new_attachment_groups:
            lines.extend(emit('[*]', new_attachment_groups[root], depth=2))
        lines += ['   struct.end', 'struct.end', '']
    return '\n'.join(lines)


def generated_file(path):
    with open(path, encoding='utf-8-sig') as handle:
        text = handle.read()
    if not text.startswith(HEADER):
        raise RuntimeError(f'Refusing to replace non-Arsenal distribution file: {path}')
    return text


def atomic_write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix='.arsenal-', dir=os.path.dirname(path))
    try:
        with os.fdopen(descriptor, 'wb') as handle:
            handle.write(data)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.remove(temporary)


def update_mod(content, incoming, defaults, warn=print):
    """Plan first, then transactionally replace only owned generated files and persistent state."""
    mod = identifier(incoming['mod'])
    identifier(incoming['weapon'])
    state_path = os.path.join(os.path.dirname(content), 'Arsenal', 'distribution.json')
    folder = os.path.join(content, 'GameLite', 'GameData', 'ItemGeneratorPrototypes')
    combined_path = os.path.join(folder, f'{mod}_ArsenalDistribution.cfg')
    records = {}
    if os.path.isfile(combined_path) and not os.path.isfile(state_path):
        raise RuntimeError(f'Combined distribution exists but its weapon settings are missing. '
                           f'Restore {state_path} from the mod project backup before importing.')
    if os.path.isfile(state_path):
        with open(state_path, encoding='utf-8') as handle:
            state = json.load(handle)
        if state.get('version') != 1 or state.get('mod') != mod:
            raise RuntimeError(f'Unsupported distribution state: {state_path}')
        records.update(state['weapons'])
    stale = []
    if os.path.isdir(folder):
        for name in sorted(os.listdir(folder)):
            match = re.fullmatch(re.escape(mod) + r'_(\w+)Distribution\.cfg', name)
            if not match or name == os.path.basename(combined_path):
                continue
            path = os.path.join(folder, name)
            text = generated_file(path)
            weapon = match[1]
            if weapon not in records and weapon != incoming['weapon']:
                records[weapon] = record_from_text(mod, weapon, text, defaults)
            stale.append(path)
    records[incoming['weapon']] = incoming
    for weapon, record in records.items():
        if record['weapon'] != weapon or record['mod'] != mod:
            raise RuntimeError(f'Mismatched distribution state for {weapon}.')
    warnings = []
    text = compose(list(records.values()), warn=warnings.append)
    if os.path.isfile(combined_path):
        generated_file(combined_path)
    legacy = os.path.join(content, 'GameLite', 'ModGameData', mod, 'ItemGeneratorPrototypes')
    for weapon in records:
        path = os.path.join(legacy, f'{identifier(weapon)}Distribution.cfg')
        if os.path.isfile(path):
            old = generated_file(path)
            if parse(old):
                raise RuntimeError(f'Obsolete active distribution file: {path}. '
                                   'Regenerate that weapon before importing.')
            stale.append(path)
    state = dict(version=1, mod=mod, weapons=dict(sorted(records.items())))
    writes = {combined_path: text.encode('utf-8'),
              state_path: (json.dumps(state, indent=2, sort_keys=True) + '\n').encode('utf-8')}
    originals = {}
    for path in list(writes) + stale:
        if os.path.isfile(path):
            with open(path, 'rb') as handle:
                originals[path] = handle.read()
        else:
            originals[path] = None
    changed = []
    try:
        for path, data in writes.items():
            atomic_write(path, data)
            changed.append(path)
        for path in stale:
            os.remove(path)
            changed.append(path)
    except Exception as error:
        rollback_errors = []
        for path in reversed(changed):
            try:
                if originals.get(path) is None:
                    os.remove(path)
                else:
                    atomic_write(path, originals[path])
            except OSError as rollback_error:
                rollback_errors.append(f'{path}: {rollback_error}')
        if rollback_errors:
            raise RuntimeError(f'{error}; distribution rollback failed: {rollback_errors}') from error
        raise
    if warnings:
        warn(f'Automatically scaled NPC shares above 100% in {len(warnings)} pool/rank/difficulty '
             'combinations. Requested and effective shares:\n' + '\n'.join(warnings))
    return len(records)
