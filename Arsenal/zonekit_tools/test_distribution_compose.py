"""Asset-free multi-weapon regression tests: python -m unittest Arsenal.zonekit_tools.test_distribution_compose."""
import copy
import itertools
import json
from pathlib import Path
import re
import tempfile
import unittest
from unittest.mock import patch

from . import test_weapon_distribution as fixtures


apply = fixtures.apply
distribution = fixtures.distribution
faction = fixtures.faction
trader = fixtures.trader


composer = distribution.distribution_compose


class CompositionTests(unittest.TestCase):
    def info(self, weapon, template='TemplatePistol', factions=(), traders=()):
        info = fixtures.DistributionTests().info(template, factions, traders)
        info.update(weapon_id=weapon, sid=f'Gun{weapon}_HG')
        return info

    def text(self, info):
        return '// Generated by Arsenal. Disabled rules emit no patches.\n' + '\n'.join(
            distribution.trader_lines(info) + distribution.npc_lines(info))

    def records(self, template='TemplatePistol', **kwargs):
        return [distribution.payload(self.info(weapon, template, **kwargs))
                for weapon in ('Alpha', 'Bravo', 'Charlie')]

    def assert_shares(self, group, expected):
        total = sum(float(item.get('Weight', '4').rstrip('f'))
                    for item in group['PossibleItems'].values())
        for sid, share in expected.items():
            weight = sum(float(item['Weight']) for item in group['PossibleItems'].values()
                         if item.get('ItemPrototypeSID') == sid)
            self.assertAlmostEqual(weight / total, share, places=9)

    def test_three_pistols_share_one_route_and_preserve_rank_difficulty_and_gate(self):
        root = 'GeneralNPC_Neutral_CloseCombat_ItemGenerator'
        original = fixtures.DistributionTests().source(root)
        records = self.records(factions=[faction()])
        text = composer.compose(records)
        self.assertEqual(text.count(f'{root} : struct.begin'), 1)
        result = apply(text, original)
        clones = [row for key, row in result.items() if key.startswith('Arsenal_')]
        self.assertEqual(len(clones), 1)
        for key, source in original[root]['ItemGenerator'].items():
            changed = copy.deepcopy(result[root]['ItemGenerator'][key])
            for index, item in source['PossibleItems'].items():
                if item.get('ItemGeneratorPrototypeSID') in distribution.DEFAULTS['pistols']:
                    changed['PossibleItems'][index]['ItemGeneratorPrototypeSID'] = item['ItemGeneratorPrototypeSID']
            self.assertEqual(changed, source)
        for group in clones[0]['ItemGenerator'].values():
            selected = group['PlayerRank'] == 'ERank::Veteran'
            self.assert_shares(group, {row['sid']: 0.03 if selected else 0 for row in records})

    def test_three_primary_weapons_preserve_other_gear_and_exact_shares(self):
        root = 'GeneralNPC_Bandit_CloseCombat_ItemGenerator'
        original = fixtures.DistributionTests().source(root)
        records = self.records('TemplateShotgun', factions=[faction('Bandit')])
        result = apply(composer.compose(records), original)
        for group in result[root]['ItemGenerator'].values():
            if group['Category'].endswith('WeaponPrimary'):
                selected = group.get('PlayerRank') == 'ERank::Veteran'
                self.assert_shares(group, {row['sid']: 0.03 if selected else 0 for row in records})
        for key, source in original[root]['ItemGenerator'].items():
            if not source['Category'].endswith('WeaponPrimary'):
                self.assertEqual(result[root]['ItemGenerator'][key], source)

    def test_three_trader_weapons_use_one_specialization_and_independent_chances(self):
        root = 'IkarTrader_TradeItemGenerator'
        infos = [self.info(name, traders=[trader(root, chance=chance)])
                 for name, chance in (('Alpha', 10), ('Bravo', 40), ('Charlie', 90))]
        original = {root: {'ItemGenerator': distribution.DEFAULTS['traders'][root]['groups']}}
        text = composer.compose([distribution.payload(info) for info in infos])
        result = apply(text, original)
        self.assertEqual(text.count(f'{root} : struct.begin'), 1)
        clones = [row for key, row in result.items() if key.startswith('Arsenal_')]
        self.assertEqual(len(clones), 1)
        ours = {item['ItemPrototypeSID']: item['Chance']
                for group in clones[0]['ItemGenerator'].values()
                for item in group['PossibleItems'].values() if item.get('ItemPrototypeSID', '').startswith('GunAlpha')
                or item.get('ItemPrototypeSID', '').startswith('GunBravo')
                or item.get('ItemPrototypeSID', '').startswith('GunCharlie')}
        self.assertEqual(ours, {'GunAlpha_HG': '0.1', 'GunBravo_HG': '0.4', 'GunCharlie_HG': '0.9'})
        self.assertEqual(result[root]['ItemGenerator']['[0]']['PossibleItems']['[0]']['Chance'], '0.5')

    def test_direct_trader_appends_all_weapons(self):
        root = 'RostokTraderSoviet_TradeItemGenerator'
        records = self.records(traders=[trader(root)])
        original = {root: {'ItemGenerator': distribution.DEFAULTS['traders'][root]['groups']}}
        result = apply(composer.compose(records), original)
        for record in records:
            self.assertIn(record['sid'], str(result))
        self.assertEqual(len(result), 1)

    def test_attachment_stock_half_effective_chance_direct_and_gated(self):
        for root, template, expected in (
                ('RostokTraderNato_TradeItemGenerator', 'TemplatePistol', 0.25),
                ('YanovTrader_TradeItemGenerator', 'TemplatePistol', 0.25),
                ('YanovTrader_TradeItemGenerator', 'TemplateShotgun', 0.075)):
            with self.subTest(root=root):
                info = self.info('Alpha', template, traders=[trader(root, chance=50)])
                info['magazines'] = [
                    {'name': 'Default', 'preinstalled': True},
                    {'name': 'Extended', 'preinstalled': False},
                    {'name': 'Shared', 'preinstalled': False, 'existing_sid': 'ExistingMag'},
                ]
                info['attachments'] = [{'sid': 'GunAlpha_AttachSilencer'}]
                record = distribution.payload(info)
                stock = record['trader_attachments'][0]
                self.assertEqual({row['ItemPrototypeSID'] for row in stock['items']},
                                 {'GunAlpha_MagExtended', 'GunAlpha_AttachSilencer'})
                for item in stock['items']:
                    self.assertAlmostEqual(float(item['Chance']), expected)
                    self.assertEqual((item['MinCount'], item['MaxCount']), ('1', '1'))
                original_groups = copy.deepcopy(distribution.DEFAULTS['traders'][root]['groups'])
                original_groups.update(distribution.DEFAULTS['traders'][root]['attachment_groups'])
                result = apply(composer.compose([record]), {root: {'ItemGenerator': original_groups}})
                attachment_groups = [group for group in result[root]['ItemGenerator'].values()
                                     if group['Category'] == 'EItemGenerationCategory::Attach']
                items = [item for group in attachment_groups for item in group['PossibleItems'].values()
                         if item.get('ItemPrototypeSID') == 'GunAlpha_MagExtended']
                self.assertEqual(len(items), 1)
                self.assertAlmostEqual(float(items[0]['Chance']), expected)

    def test_attachment_stock_multi_weapon_reimport_and_disable(self):
        root = 'IkarTrader_TradeItemGenerator'
        infos = [self.info(name, traders=[trader(root, chance=40)])
                 for name in ('Alpha', 'Bravo')]
        for info in infos:
            info['magazines'] = [{'name': 'Extended', 'preinstalled': False}]
        with tempfile.TemporaryDirectory() as temporary:
            content = Path(temporary) / 'Content'
            for info in infos:
                composer.update_mod(str(content), distribution.payload(info), distribution.DEFAULTS)
            path = content / 'GameLite' / 'GameData' / 'ItemGeneratorPrototypes' / 'TestMod_ArsenalDistribution.cfg'
            text = path.read_text()
            self.assertEqual(text.count(f'{root} : struct.begin'), 1)
            self.assertEqual(text.count('Category = EItemGenerationCategory::Attach'), 1)
            self.assertIn('ItemPrototypeSID = GunAlpha_MagExtended', text)
            self.assertIn('ItemPrototypeSID = GunBravo_MagExtended', text)
            before = path.read_bytes()
            composer.update_mod(str(content), distribution.payload(infos[0]), distribution.DEFAULTS)
            self.assertEqual(path.read_bytes(), before)
            infos[0]['cfg'].stock_custom_attachments = False
            composer.update_mod(str(content), distribution.payload(infos[0]), distribution.DEFAULTS)
            text = path.read_text()
            self.assertNotIn('GunAlpha_MagExtended', text)
            self.assertIn('GunAlpha_HG', text)
            self.assertIn('GunBravo_MagExtended', text)
            infos[1]['cfg'].traders[0].enabled = False
            composer.update_mod(str(content), distribution.payload(infos[1]), distribution.DEFAULTS)
            self.assertNotIn('GunBravo_MagExtended', path.read_text())

    def test_custom_attachments_support_every_trader(self):
        for root in distribution.DEFAULTS['traders']:
            with self.subTest(trader=root):
                info = self.info('Alpha', traders=[trader(root)])
                info['magazines'] = [{'name': 'Extended', 'preinstalled': False}]
                record = distribution.payload(info)
                original = copy.deepcopy(distribution.DEFAULTS['traders'][root]['groups'])
                original.update(distribution.DEFAULTS['traders'][root]['attachment_groups'])
                result = apply(composer.compose([record]), {root: {'ItemGenerator': original}})
                entries = [item for group in result[root]['ItemGenerator'].values()
                           if group['Category'] == 'EItemGenerationCategory::Attach'
                           for item in group['PossibleItems'].values()
                           if item.get('ItemPrototypeSID') == 'GunAlpha_MagExtended']
                self.assertEqual(len(entries), 1)
                route = distribution.trader_route(info['cfg'], root)[1]
                self.assertAlmostEqual(float(entries[0]['Chance']), 0.2 * (route[3] if route else 1))

    def test_order_independent_and_hundred_percent_shared_without_vanilla(self):
        records = [distribution.payload(self.info(
            name, factions=[faction(role_percent=percent, rank_percent=100)]))
                   for name, percent in (('Alpha', 25), ('Bravo', 25), ('Charlie', 50))]
        text = composer.compose(records)
        for order in itertools.permutations(records):
            self.assertEqual(composer.compose(order), text)
        result = apply(text, fixtures.DistributionTests().source('GeneralNPC_Neutral_CloseCombat_ItemGenerator'))
        clone = next(row for key, row in result.items() if key.startswith('Arsenal_'))
        for group in clone['ItemGenerator'].values():
            if group['PlayerRank'] == 'ERank::Veteran':
                self.assertEqual(len(group['PossibleItems']), 3)
                self.assert_shares(group, {'GunAlpha_HG': 0.25, 'GunBravo_HG': 0.25, 'GunCharlie_HG': 0.5})

    def test_overcommitted_shares_are_proportionally_scaled_with_explicit_warning(self):
        records = self.records(factions=[faction(role_percent=50, rank_percent=100)])
        warnings = []
        text = composer.compose(records, warn=warnings.append)
        self.assertTrue(warnings)
        self.assertRegex(warnings[0], r'exceeds 100%.*Veteran.*Alpha.*Bravo.*Charlie')
        self.assertIn('Automatically scaled proportionally', warnings[0])
        result = apply(text, fixtures.DistributionTests().source('GeneralNPC_Neutral_CloseCombat_ItemGenerator'))
        clone = next(row for key, row in result.items() if key.startswith('Arsenal_'))
        for group in clone['ItemGenerator'].values():
            if group['PlayerRank'] == 'ERank::Veteran':
                self.assertEqual(len(group['PossibleItems']), 3)
                self.assert_shares(group, {row['sid']: 1 / 3 for row in records})

    def test_all_templates_support_combined_hundred_percent_rules(self):
        for template in distribution.PRESETS:
            rules = []
            for name, _ in distribution.FACTIONS:
                rule = faction(name, role_percent=100, rank_percent=100)
                for role, value in rule.roles.items():
                    value.enabled = role in distribution.available_roles(name)
                    value.percent = 100
                for value in rule.ranks.values():
                    value.enabled, value.percent = True, 100
                rules.append(rule)
            records = self.records(template, factions=rules)
            warnings = []
            text = composer.compose(records, warn=warnings.append)
            roots = re.findall(r'^(\w+) : struct.begin', text, re.M)
            self.assertEqual(len(roots), len(set(roots)))
            original = {sid: {'ItemGenerator': row['groups']}
                        for sid, row in distribution.DEFAULTS['npc'].items()}
            apply(text, original)
            self.assertTrue(warnings)

    def test_difficulty_specific_ammo_is_preserved(self):
        base = {
            'Category': 'EItemGenerationCategory::WeaponPrimary', 'PlayerRank': 'ERank::Veteran',
            'PossibleItems': {'[0]': {'ItemPrototypeSID': 'Donor', 'Weight': '10'}}}
        operations = []
        for weapon, ammo in (('Alpha', 2), ('Bravo', 9)):
            variants = {}
            for index, difficulty in enumerate(composer.DIFFICULTIES):
                group = copy.deepcopy(base)
                group['Diff'] = f'EGameDifficulty::{difficulty}'
                group['PossibleItems']['[1]'] = dict(
                    ItemPrototypeSID=f'Gun{weapon}_HG', Weight='10',
                    AmmoMaxCount=str(ammo if difficulty == 'Stalker' else 1))
                variants[f'[{index}]'] = group
            operations.append(dict(version=1, mod='TestMod', weapon=weapon, sid=f'Gun{weapon}_HG',
                                   operations=[dict(root='Test', group='[0]', route=None, kind='npc',
                                                    base={'[0]': base}, variants=variants)]))
        result = apply(composer.compose(operations), {'Test': {'ItemGenerator': {'[0]': base}}})
        for group in result['Test']['ItemGenerator'].values():
            ours = {item['ItemPrototypeSID']: item for item in group['PossibleItems'].values()}
            for weapon, ammo in (('Alpha', 2), ('Bravo', 9)):
                expected = str(ammo if 'Stalker' in group['Diff'] else 1)
                self.assertEqual(ours[f'Gun{weapon}_HG']['AmmoMaxCount'], expected)

    def test_legacy_migration_reimport_disable_and_persistent_other_weapons(self):
        with tempfile.TemporaryDirectory() as temporary:
            content = Path(temporary) / 'Mod' / 'Content'
            folder = content / 'GameLite' / 'GameData' / 'ItemGeneratorPrototypes'
            folder.mkdir(parents=True)
            infos = [self.info(name, factions=[faction()], traders=[trader()])
                     for name in ('Alpha', 'Bravo', 'Charlie')]
            for info in infos:
                (folder / f'TestMod_{info["weapon_id"]}Distribution.cfg').write_text(self.text(info))
            unrelated = folder / 'Other.cfg'
            unrelated.write_text('// User-owned CFG\n')
            incoming = distribution.payload(infos[0])
            self.assertEqual(composer.update_mod(str(content), incoming, distribution.DEFAULTS), 3)
            combined = folder / 'TestMod_ArsenalDistribution.cfg'
            self.assertEqual({path.name for path in folder.iterdir()}, {combined.name, unrelated.name})
            state_path = content.parent / 'Arsenal' / 'distribution.json'
            state = json.loads(state_path.read_text())
            self.assertEqual(set(state['weapons']), {'Alpha', 'Bravo', 'Charlie'})
            before = combined.read_bytes()
            composer.update_mod(str(content), incoming, distribution.DEFAULTS)
            self.assertEqual(combined.read_bytes(), before)
            composer.update_mod(str(content), distribution.payload(self.info('Alpha')), distribution.DEFAULTS)
            self.assertNotIn('GunAlpha_HG', combined.read_text())
            self.assertIn('GunBravo_HG', combined.read_text())
            self.assertIn('GunCharlie_HG', combined.read_text())
            self.assertEqual(unrelated.read_text(), '// User-owned CFG\n')

    def test_invalid_merge_leaves_mod_unchanged(self):
        with tempfile.TemporaryDirectory() as temporary:
            content = Path(temporary) / 'Content'
            first = distribution.payload(self.info(
                'Alpha', factions=[faction(role_percent=70, rank_percent=100)]))
            composer.update_mod(str(content), first, distribution.DEFAULTS)
