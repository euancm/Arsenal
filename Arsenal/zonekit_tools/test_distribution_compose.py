    def test_missing_state_does_not_silently_discard_other_weapons(self):
        with tempfile.TemporaryDirectory() as temporary:
            content = Path(temporary) / 'Content'
            record = distribution.payload(self.info('Alpha', traders=[trader()]))
            composer.update_mod(str(content), record, distribution.DEFAULTS)
            combined = (content / 'GameLite' / 'GameData' / 'ItemGeneratorPrototypes'
                        / 'TestMod_ArsenalDistribution.cfg')
            before = combined.read_bytes()
            (content.parent / 'Arsenal' / 'distribution.json').unlink()
            with self.assertRaisesRegex(RuntimeError, 'weapon settings are missing'):
                composer.update_mod(str(content), record, distribution.DEFAULTS)
            self.assertEqual(combined.read_bytes(), before)


